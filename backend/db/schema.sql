-- Starter schema; no DROP statements or embedded credentials.
CREATE TABLE IF NOT EXISTS customers (
 id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 email TEXT NOT NULL UNIQUE, password TEXT NOT NULL, enabled BOOLEAN NOT NULL DEFAULT TRUE,
 first_name TEXT NOT NULL, last_name TEXT NOT NULL
);
CREATE TABLE IF NOT EXISTS restaurants (
 id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 name TEXT NOT NULL, address TEXT, phone TEXT, image_url TEXT
);
CREATE TABLE IF NOT EXISTS menu_items (
 id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 restaurant_id BIGINT NOT NULL REFERENCES restaurants(id),
 name TEXT NOT NULL, description TEXT, price NUMERIC(12,2) NOT NULL CHECK (price >= 0), image_url TEXT
);
CREATE TABLE IF NOT EXISTS carts (
 id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 customer_id BIGINT NOT NULL UNIQUE REFERENCES customers(id), total_price NUMERIC(12,2) NOT NULL DEFAULT 0 CHECK (total_price >= 0)
);
CREATE TABLE IF NOT EXISTS order_items (
 id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 menu_item_id BIGINT NOT NULL REFERENCES menu_items(id), cart_id BIGINT NOT NULL REFERENCES carts(id),
 price NUMERIC(12,2) NOT NULL CHECK (price >= 0), quantity INTEGER NOT NULL CHECK (quantity > 0),
 UNIQUE (cart_id, menu_item_id)
);
